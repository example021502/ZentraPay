// Always add inline comments for code readability and maintenance
package com.zentrapay.backend.entity;

import com.zentrapay.backend.service.common.Datatypes;
import jakarta.persistence.*;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.annotations.UpdateTimestamp;
import org.hibernate.type.SqlTypes;
import tools.jackson.databind.JsonNode;

import java.math.BigDecimal;
import java.time.LocalDateTime;
import java.util.UUID;

// JPA Entity representing transaction history and ledger legs across ZentraPay corridors
@Entity
@Data // Automatically generates getters, setters, equals, hashCode, and toString
@Builder
@NoArgsConstructor
@AllArgsConstructor
@Table(
        name = "transactions",
        indexes = {
                // High-frequency lookup by unique internal transaction reference
                @Index(name = "idx_txn_internal_ref", columnList = "internal_reference_id", unique = true),
                // External reference lookup for payment gateway, bank, and telco webhooks
                @Index(name = "idx_txn_external_ref", columnList = "external_reference_id"),
                // Groups related double-entry legs (e.g., debit and credit legs of one transfer)
                @Index(name = "idx_txn_entry_id", columnList = "entry_id"),
                // Sender history query optimization
                @Index(name = "idx_txn_sender_created", columnList = "sender_id, created_at"),
                // Receiver history query optimization
                @Index(name = "idx_txn_receiver_created", columnList = "receiver_id, created_at"),
                // Worker poller query optimization for pending/in-flight transactions
                @Index(name = "idx_txn_status_created", columnList = "status, created_at")
        }
)
public class TransactionModel {

    // Primary key for the transaction/ledger row
    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    @Column(name = "id", nullable = false, updatable = false)
    private UUID id;

    // Correlation/journal identifier linking related double-entry legs together
    @Column(name = "entry_id", nullable = false, length = 64, updatable = false)
    private String entryId;

    // Unique internal reference generated by ZentraPay (e.g., zp_...)
    @Column(name = "internal_reference_id", nullable = false, length = 64, updatable = false)
    private String internalReferenceId;

    // Nullable at initiation; populated asynchronously when gateway, bank, or telco responds
    @Column(name = "external_reference_id", length = 120)
    private String externalReferenceId;

    // Client or caller idempotency key to prevent duplicate transaction creation on retry
    @Column(name = "idempotency_key", nullable = false, unique = true, length = 120, updatable = false)
    private String idempotencyKey;

    // Principal amount in the source currency
    @Column(name = "amount", nullable = false, precision = 19, scale = 4, updatable = false)
    private BigDecimal amount;

    // Transaction/service fee charged on this operation (defaults to zero when fee-free)
    @Builder.Default
    @Column(name = "fee_amount", nullable = false, precision = 19, scale = 4, updatable = false)
    private BigDecimal feeAmount = BigDecimal.ZERO;

    // Applied FX rate between source and destination currencies (1.0 when same-currency)
    @Column(name = "exchange_rate", precision = 24, scale = 10, updatable = false)
    private BigDecimal exchangeRate;

    // Applied rate id for traceability
    @Column(name = "rate_id")
    private UUID rateId;

    // ISO 4217 source currency code (e.g., KES, NGN, GHS)
    @Column(name = "source_currency_code", nullable = false, length = 3, updatable = false)
    private String sourceCurrencyCode;

    // ISO 4217 destination currency code (e.g., KES, NGN, GHS)
    @Column(name = "destination_currency_code", nullable = false, length = 3, updatable = false)
    private String destinationCurrencyCode;

    // Amount received/settled in destination currency for cross-currency or converted flows
    @Column(name = "destination_amount", precision = 19, scale = 4)
    private BigDecimal destinationAmount;

    // Lifecycle status of the transaction (e.g., PENDING, COMPLETED, FAILED, REVERSED)
    @Enumerated(EnumType.STRING)
    @Column(name = "status", nullable = false, length = 20)
    private Datatypes.TransactionStatus status;

    // High-level transaction type (e.g., P2P_TRANSFER, REMITTANCE, BILL_PAYMENT, DEPOSIT)
    @Enumerated(EnumType.STRING)
    @Column(name = "transaction_type", nullable = false, length = 30, updatable = false)
    private Datatypes.TransactionType transactionType;

    // Payment gateway or provider ID used to process the transaction, if applicable
    @Column(name = "gateway_id")
    private UUID gatewayId;

    // Sender user ID (nullable for external/system-originated credits)
    @Column(name = "sender_id", updatable = false)
    private UUID senderId;

    // Snapshot of sender name at transaction time for historical receipt accuracy
    @Column(name = "sender_name", length = 150, updatable = false)
    private String senderName;

    // Snapshot of sender email at transaction time
    @Column(name = "sender_email", length = 150, updatable = false)
    private String senderEmail;

    // Snapshot of sender phone number at transaction time
    @Column(name = "sender_phone_number", length = 20, updatable = false)
    private String senderPhoneNumber;

    // Receiver user ID (nullable for external bank/MoMo/merchant payouts)
    @Column(name = "receiver_id", updatable = false)
    private UUID receiverId;

    // Snapshot of receiver name at transaction time for historical receipt accuracy
    @Column(name = "receiver_name", length = 150, updatable = false)
    private String receiverName;

    // Snapshot of receiver email at transaction time
    @Column(name = "receiver_email", length = 150, updatable = false)
    private String receiverEmail;

    // Snapshot of receiver phone number at transaction time
    @Column(name = "receiver_phone_number", length = 20, updatable = false)
    private String receiverPhoneNumber;

    // Target account, phone, wallet, or meter/biller identifier used for routing
    @Column(name = "destination_identifier", length = 100, updatable = false)
    private String destinationIdentifier;

    // Human-readable reason or narration for the transaction
    @Column(name = "purpose", nullable = false, length = 255, updatable = false)
    private String purpose;

    // Failure or reversal explanation when a transaction does not complete normally
    @Column(name = "failure_reason", length = 255)
    private String failureReason;

    // Flexible JSONB payload for gateway responses, bill tokens, or extra audit fields
    @JdbcTypeCode(SqlTypes.JSON)
    @Column(name = "metadata", columnDefinition = "jsonb")
    private JsonNode metadata;

    // Optimistic lock version to guard against concurrent status/webhook updates
    @Version
    @Column(name = "version", nullable = false)
    private Long version;

    // Timestamp when the transaction record was created
    @CreationTimestamp
    @Column(name = "created_at", nullable = false, updatable = false)
    private LocalDateTime createdAt;

    // Timestamp automatically updated when transaction status or audit fields change
    @UpdateTimestamp
    @Column(name = "updated_at", nullable = false)
    private LocalDateTime updatedAt;
}