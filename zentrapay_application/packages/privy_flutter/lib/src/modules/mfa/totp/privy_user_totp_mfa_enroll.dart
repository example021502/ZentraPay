import 'package:privy_flutter/src/core/privy_plug_in_module.dart';
import 'package:privy_flutter/src/utils/result.dart';
import 'package:privy_flutter/src/modules/privy_user/privy_user.dart';
import 'package:privy_flutter/src/modules/mfa/totp/totp_secret.dart';

/// TOTP MFA enrollment operations.
///
/// Access via `user.mfa.totp.enroll`.
abstract interface class PrivyUserTotpMfaEnroll extends PrivyPluginModule {
  /// Constructor that initializes the module with a method channel handler.
  PrivyUserTotpMfaEnroll(super.channelHandler);

  /// Generate a TOTP secret for enrollment.
  ///
  /// Returns a [TotpSecret] containing:
  /// - [TotpSecret.secret]: The secret key for manual entry
  /// - [TotpSecret.authUrl]: OTP Auth URL for QR code generation
  ///
  /// Display the QR code (from [TotpSecret.authUrl]) or the manual entry key
  /// (from [TotpSecret.secret]) to the user so they can add it to their
  /// authenticator app.
  Future<Result<TotpSecret>> generateSecret();

  /// Complete TOTP MFA enrollment with a [code] from the authenticator app.
  ///
  /// The user must enter a code generated by their authenticator app after
  /// scanning the QR code or entering the secret manually.
  ///
  /// Returns the updated [PrivyUser] with TOTP MFA enrolled.
  Future<Result<PrivyUser>> submit(String code);
}
